export type DbStrings = typeof zh
const strings: DbStrings = { ...zh }
export function t(k: keyof DbStrings, vars?: Record<string, string | number>) {
  let s = strings[k]
  if (vars) for (const [a, b] of Object.entries(vars)) s = s.replace(`{${a}}`, String(b))
  return s
}

