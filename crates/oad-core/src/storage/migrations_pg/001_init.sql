-- Postgres 版的表结构，和 migrations/ 里 SQLite 的一一对应：INTEGER → BIGINT，BLOB → BYTEA，
-- AUTOINCREMENT → 自增列；文本都用 COLLATE "C"（按字节比较、排序，和 SQLite 一样，位置字符串靠这个排序）。
CREATE TABLE workspaces (
    id TEXT COLLATE "C" PRIMARY KEY,
    name TEXT COLLATE "C" NOT NULL,
    created_at BIGINT NOT NULL
);

CREATE TABLE users (
    id TEXT COLLATE "C" PRIMARY KEY,
    name TEXT COLLATE "C" NOT NULL,
    email TEXT COLLATE "C",
    password_hash TEXT COLLATE "C",
    external_id TEXT COLLATE "C" UNIQUE,
    kind TEXT COLLATE "C" NOT NULL DEFAULT 'user',
    created_at BIGINT NOT NULL
);
-- 邮箱不分大小写唯一（SQLite 是列上的 COLLATE NOCASE）
CREATE UNIQUE INDEX users_email ON users (lower(email));

CREATE TABLE members (
    workspace_id TEXT COLLATE "C" NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role TEXT COLLATE "C" NOT NULL,
    PRIMARY KEY (workspace_id, user_id)
);
CREATE INDEX members_user ON members(user_id);

CREATE TABLE sessions (
    token_hash TEXT COLLATE "C" PRIMARY KEY,
    user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    created_at BIGINT NOT NULL,
    expires_at BIGINT NOT NULL
);
CREATE INDEX sessions_user ON sessions(user_id);

CREATE TABLE pages (
    id TEXT COLLATE "C" PRIMARY KEY,
    workspace_id TEXT COLLATE "C" NOT NULL REFERENCES workspaces(id),
    parent_id TEXT COLLATE "C" REFERENCES pages(id),
    position TEXT COLLATE "C" NOT NULL,
    title TEXT COLLATE "C" NOT NULL DEFAULT '',
    icon TEXT COLLATE "C",
    created_by TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    updated_at BIGINT NOT NULL,
    deleted_at BIGINT
);
CREATE INDEX pages_tree ON pages(workspace_id, parent_id, position);
CREATE INDEX pages_parent ON pages(parent_id);

-- 正文：快照 + 之后的增量（Yrs v1）
CREATE TABLE doc_snapshots (
    page_id TEXT COLLATE "C" PRIMARY KEY REFERENCES pages(id) ON DELETE CASCADE,
    state BYTEA NOT NULL,
    updated_at BIGINT NOT NULL
);

CREATE TABLE doc_updates (
    seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id TEXT COLLATE "C" NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
    data BYTEA NOT NULL,
    created_at BIGINT NOT NULL
);
CREATE INDEX doc_updates_page ON doc_updates(page_id, seq);

-- 历史版本（第 5 阶段用）
CREATE TABLE doc_versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    page_id TEXT COLLATE "C" NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
    state BYTEA NOT NULL,
    label TEXT COLLATE "C",
    created_by TEXT COLLATE "C",
    created_at BIGINT NOT NULL
);
CREATE INDEX doc_versions_page ON doc_versions(page_id, created_at);
