-- Agent：users 里一行（kind = 'agent'），这里放 Agent 才有的字段
CREATE TABLE agents (
    id TEXT COLLATE "C" PRIMARY KEY REFERENCES users(id),
    workspace_id TEXT COLLATE "C" NOT NULL REFERENCES workspaces(id),
    name TEXT COLLATE "C" NOT NULL,
    about TEXT COLLATE "C" NOT NULL DEFAULT '',
    scope TEXT COLLATE "C" NOT NULL,
    token_hash TEXT COLLATE "C" UNIQUE,
    webhook TEXT COLLATE "C",
    -- 签 webhook 要用原文，只能存原文
    webhook_secret TEXT COLLATE "C" NOT NULL,
    created_by TEXT COLLATE "C",
    created_at BIGINT NOT NULL,
    last_used_at BIGINT,
    revoked_at BIGINT
);
CREATE UNIQUE INDEX agents_name ON agents(workspace_id, name);

-- 哪个 Yjs client id 是谁写的
CREATE TABLE doc_clients (
    page_id TEXT COLLATE "C" NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
    client_id BIGINT NOT NULL,
    principal_kind TEXT COLLATE "C" NOT NULL,
    principal_id TEXT COLLATE "C" NOT NULL,
    created_at BIGINT NOT NULL,
    PRIMARY KEY (page_id, client_id)
);

CREATE TABLE comment_threads (
    id TEXT COLLATE "C" PRIMARY KEY,
    page_id TEXT COLLATE "C" NOT NULL REFERENCES pages(id) ON DELETE CASCADE,
    block_id TEXT COLLATE "C",
    anchor_start TEXT COLLATE "C",
    anchor_end TEXT COLLATE "C",
    quote TEXT COLLATE "C",
    created_by TEXT COLLATE "C" NOT NULL,
    created_at BIGINT NOT NULL,
    resolved_at BIGINT,
    resolved_by TEXT COLLATE "C"
);
CREATE INDEX comment_threads_page ON comment_threads(page_id, created_at);

CREATE TABLE comments (
    id TEXT COLLATE "C" PRIMARY KEY,
    thread_id TEXT COLLATE "C" NOT NULL REFERENCES comment_threads(id) ON DELETE CASCADE,
    author_kind TEXT COLLATE "C" NOT NULL,
    author_id TEXT COLLATE "C" NOT NULL,
    body TEXT COLLATE "C" NOT NULL,
    created_at BIGINT NOT NULL,
    edited_at BIGINT,
    deleted_at BIGINT
);
CREATE INDEX comments_thread ON comments(thread_id, created_at);

-- Agent 的通知；id 是游标
CREATE TABLE agent_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workspace_id TEXT COLLATE "C" NOT NULL,
    agent_id TEXT COLLATE "C" NOT NULL REFERENCES agents(id),
    kind TEXT COLLATE "C" NOT NULL,
    data TEXT COLLATE "C" NOT NULL,
    created_at BIGINT NOT NULL,
    delivered_at BIGINT,
    acked_at BIGINT,
    attempts BIGINT NOT NULL DEFAULT 0,
    error TEXT COLLATE "C",
    -- 下次投 webhook 的时间；NULL = 不用投（没有 webhook、已送到或放弃了）
    next_attempt_at BIGINT
);
CREATE INDEX agent_notifications_agent ON agent_notifications(agent_id, id);
CREATE INDEX agent_notifications_ws ON agent_notifications(workspace_id, id);
CREATE INDEX agent_notifications_due ON agent_notifications(next_attempt_at) WHERE next_attempt_at IS NOT NULL;

-- 人的通知（收件箱）
CREATE TABLE user_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT COLLATE "C" NOT NULL REFERENCES users(id),
    workspace_id TEXT COLLATE "C" NOT NULL,
    kind TEXT COLLATE "C" NOT NULL,
    data TEXT COLLATE "C" NOT NULL,
    created_at BIGINT NOT NULL,
    read_at BIGINT
);
CREATE INDEX user_notifications_user ON user_notifications(user_id, id);
