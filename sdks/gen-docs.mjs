// 从 sdks/operations.json 生成“接口对照表”（点路径 → Python / Go / Rust / JS 的写法），写进 docs/zh|en/sdks.md 的
// <!-- operations:start --> 和 <!-- operations:end --> 之间。Go 的名字到生成的代码里核对一遍，对不上就报错。
//   node sdks/gen-docs.mjs           写
//   node sdks/gen-docs.mjs --check   只比较，过期了退出 1
import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'

const root = fileURLToPath(new URL('..', import.meta.url))
const spec = JSON.parse(readFileSync(root + 'docs/openapi.json', 'utf8'))
const table = JSON.parse(readFileSync(root + 'sdks/operations.json', 'utf8'))
const goSrc = readFileSync(root + 'sdks/go/zz_generated_resources.go', 'utf8')

// operationId → 方法和路径
const http = new Map()
for (const [path, item] of Object.entries(spec.paths))
  for (const [m, op] of Object.entries(item)) if (op?.operationId) http.set(op.operationId, `${m.toUpperCase()} ${path}`)

const ACRONYMS = { id: 'ID', ids: 'IDs', url: 'URL', csv: 'CSV', html: 'HTML', ws: 'WS', jwt: 'JWT' }
const pascal = (s) => s.split('_').map((w) => ACRONYMS[w] ?? w[0].toUpperCase() + w.slice(1)).join('')

const errors = []
const rows = []
for (const [id, e] of Object.entries(table.operations)) {
  const parts = e.name.split('.')
  const method = parts.at(-1)
  const res = parts.slice(0, -1)
  const py = `client.${e.name}()`
  const goRes = res.map(pascal)
  const go = `client.${[...goRes, pascal(method)].join('.')}()`
  if (res.length) {
    const svc = goRes.join('') + 'Service'
    if (!goSrc.includes(`func (r *${svc}) ${pascal(method)}(`)) errors.push(`Go 里没有 ${svc}.${pascal(method)}（${e.name}）`)
  } else if (!goSrc.includes(`func (c *Client) ${pascal(method)}(`)) errors.push(`Go 里没有 Client.${pascal(method)}（${e.name}）`)
  const rs = `client.${[...res.map((r) => r + '()'), method + '()'].join('.')}`
  const js = `client.${e.js}()`
  const extra = []
  if (e.paginate) extra.push('翻页|paging')
  if (e.sse) extra.push('事件流|stream')
  if (e.upload) extra.push('上传|upload')
  if (e.download) extra.push('下载|download')
  rows.push({ name: e.name, py, go, rs, js, http: http.get(id), extra })
}
if (errors.length) {
  console.error(errors.map((x) => '✗ ' + x).join('\n'))
  process.exit(1)
}

function render(lang) {
  const zh = lang === 'zh'
  const head = zh
    ? '| 点路径 | Python | Go | Rust | JS | HTTP |\n| --- | --- | --- | --- | --- | --- |'
    : '| Name | Python | Go | Rust | JS | HTTP |\n| --- | --- | --- | --- | --- | --- |'
  const body = rows
    .map((r) => {
      const note = r.extra.map((x) => x.split('|')[zh ? 0 : 1]).join(zh ? '、' : ', ')
      return `| \`${r.name}\`${note ? ` (${note})` : ''} | \`${r.py}\` | \`${r.go}\` | \`${r.rs}\` | \`${r.js}\` | \`${r.http}\` |`
    })
    .join('\n')
  const intro = zh
    ? `<!-- 由 node sdks/gen-docs.mjs 从 sdks/operations.json 生成，不要手改 -->\n${rows.length} 个接口。Go 的方法第一个参数是 \`ctx\`；Rust 的要 \`.await\`；翻页的接口 Go 另有 \`ListAll\`、Rust 另有 \`list_all\`、JS 另有 \`each*\`。`
    : `<!-- generated by node sdks/gen-docs.mjs from sdks/operations.json; do not edit -->\n${rows.length} operations. Go methods take \`ctx\` first; Rust calls need \`.await\`; paginated lists also have \`ListAll\` (Go), \`list_all\` (Rust) and \`each*\` (JS).`
  return `${intro}\n\n${head}\n${body}`
}

const check = process.argv.includes('--check')
let stale = false
for (const lang of ['zh', 'en']) {
  const f = `${root}docs/${lang}/sdks.md`
  const s = readFileSync(f, 'utf8')
  const re = /(<!-- operations:start -->)[\s\S]*?(<!-- operations:end -->)/
  if (!re.test(s)) throw new Error(`${f} 里没有 <!-- operations:start --> / <!-- operations:end -->`)
  const next = s.replace(re, `$1\n${render(lang)}\n$2`)
  if (next === s) continue
  if (check) {
    console.error(`✗ docs/${lang}/sdks.md 的接口对照表过期了：node sdks/gen-docs.mjs`)
    stale = true
  } else {
    writeFileSync(f, next)
    console.log(`→ docs/${lang}/sdks.md`)
  }
}
if (stale) process.exit(1)
if (check) console.log(`✓ 接口对照表是最新的（${rows.length} 个）`)
